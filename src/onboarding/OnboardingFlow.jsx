/** The statement is being read in place: real steps as they happen, the two profile questions while we wait, and - only if needed -
 *  the password, the key or the problem, right here. */
function Intake({ go, status, controlRef, onPickFile, onToast, addMode, ready, household, setHousehold, householdAnswered, setHouseholdAnswered, priorities, setPriorities }) {
  const [pwd, setPwd] = useState("");
  const [key, setKey] = useState("");
  const inputRef = useRef(null);
  const [q, setQ] = useState(() => (addMode ? "done" : !householdAnswered ? "q1" : !(priorities && priorities.length) ? "q2" : "done"));
  // The steps are folded from every status the reader reported, so even an instant read shows each real step it took.
  const steps = [];
  ((status && status.log) || []).forEach((e) => {
    if (e.stage === "imported") { steps.forEach((x) => { x.done = true; }); steps.push({ stage: "saved", label: "Saved " + e.count + " transactions on this device", done: true }); return; }
    if (!e.label || ["error", "needs_key", "needs_password"].includes(e.stage)) return;
    steps.forEach((x) => { x.done = true; });
    const i = steps.findIndex((x) => x.stage === e.stage);
    if (i >= 0) { steps[i].label = e.label; steps[i].done = false; } else steps.push({ stage: e.stage, label: e.label, done: false });
  });
  useEffect(() => { if (ready && q === "done") go("reading"); }, [ready, q]); // eslint-disable-line react-hooks/exhaustive-deps
  const stage = status ? status.stage : null;
  const unreconciled = stage === "unreconciled";
  const stalled = ["error", "needs_key", "needs_password", "unreconciled"].includes(stage);
  const inr = (n) => "\u20B9" + Math.abs(Math.round(n)).toLocaleString("en-IN");
  useEffect(() => { if (unreconciled && onToast) onToast("This statement doesn\u2019t add up. Please check it."); }, [unreconciled]); // eslint-disable-line react-hooks/exhaustive-deps
  const qGo = (to) => setQ((cur) => (cur === "q1" ? (priorities && priorities.length ? "done" : "q2") : "done"));
  return (
    <>
      <input ref={inputRef} type="file" accept=".pdf,.csv,.xlsx,.xls" style={{ display: "none" }} onChange={(e) => { const f = e.target.files && e.target.files[0]; e.target.value = ""; if (f) onPickFile(f); }} />
      <div className="kicker">{ready ? "Done reading" : stalled ? "One thing first" : "One moment"}</div>
      <h2>{ready ? "Your statement is read" : "Reading your statement\u2026"}</h2>
      <div className="feed" aria-live="polite">
        {steps.map((x, i) => (
          <div key={x.stage + i} className="ln show">{x.done ? <Icon name="check" /> : stalled ? <Icon name="dots" /> : <span className="spin" />}<span>{x.label}</span></div>
        ))}
      </div>
      {stage === "needs_password" && (
        <div className="card" role="alert">
          <div className="lbl">This PDF is password-protected</div>
          <p className="hint" style={{ marginTop: 0 }}>{status.wrong ? "That password didn\u2019t work. " : ""}Banks usually use your date of birth or customer ID. The password stays in this browser.</p>
          <div className="row" style={{ gap: 10 }}>
            <input type="password" aria-label="PDF password" value={pwd} onChange={(e) => setPwd(e.target.value)} onKeyDown={(e) => { if (e.key === "Enter" && pwd) controlRef.current.submitPassword(pwd); }}
              style={{ flex: 1, padding: "10px 12px", borderRadius: 10, border: "1px solid var(--line, #ddd)", font: "inherit" }} />
            <button className="btn teal" disabled={!pwd} onClick={() => controlRef.current.submitPassword(pwd)}>Unlock</button>
          </div>
        </div>
      )}
      {(stage === "needs_key" || (stage === "error" && status.canAddKey)) && (
        <div className="card" role="alert">
          <div className="lbl">{stage === "needs_key" ? "Reading a PDF needs your Gemini key" : status.message}</div>
          <p className="hint" style={{ marginTop: 0 }}>The key is free from Google, is kept only in this browser, and is used only to read statements. CSV and Excel files don{"\u2019"}t need one. <a href="https://aistudio.google.com/app/apikey" target="_blank" rel="noreferrer">Get a free key</a></p>
          <div className="row" style={{ gap: 10 }}>
            <input type="password" aria-label="Gemini API key" placeholder="Paste your Gemini API key" value={key} onChange={(e) => setKey(e.target.value)} onKeyDown={(e) => { if (e.key === "Enter" && key.trim()) controlRef.current.submitKey(key); }}
              style={{ flex: 1, padding: "10px 12px", borderRadius: 10, border: "1px solid var(--line, #ddd)", font: "inherit" }} />
            <button className="btn teal" disabled={!key.trim()} onClick={() => controlRef.current.submitKey(key)}>Save and continue</button>
          </div>
        </div>
      )}
      {unreconciled && (
        <div className="card" role="alert" data-testid="unreconciled" style={{ borderColor: "#9c4a34", background: "rgba(156,74,52,0.07)" }}>
          <div className="lbl" style={{ color: "#9c4a34" }}>This statement doesn{"\u2019"}t add up</div>
          {status.csv ? (
            <p className="hint" style={{ marginTop: 0 }}>The running balance in this file breaks in {status.breaks} place{status.breaks === 1 ? "" : "s"}, so a row may be missing or misread. Your cash and anything built on it could be wrong.</p>
          ) : (
            <p className="hint" style={{ marginTop: 0 }}>
              {status.opening !== null && status.opening !== undefined ? <>{status.isCard ? "Previous balance" : "Opening"} {inr(status.opening)}, plus the {status.count} transactions I read, comes to {inr(status.implied)}. </> : null}
              The statement says {status.isCard ? "outstanding" : "closing"} {inr(status.closing)}. That is {inr(status.diff)} {status.diff > 0 ? "more" : "less"} than it should be{status.gaps ? ", with " + status.gaps + " jump" + (status.gaps === 1 ? "" : "s") + " in the running balance" : ""}. A transaction may be missing or misread, so your cash and anything built on it could be wrong.
            </p>
          )}
          <div className="row" style={{ gap: 10 }}>
            <button className="btn ghost" onClick={() => inputRef.current && inputRef.current.click()}>Check the file</button>
            <button className="btn teal" data-testid="continue-anyway" onClick={() => controlRef.current && controlRef.current.proceedAnyway && controlRef.current.proceedAnyway()}>Continue anyway</button>
          </div>
        </div>
      )}
      {stage === "error" && !status.canAddKey && (
        <div className="card" role="alert"><div className="lbl">I couldn{"\u2019"}t use that file</div><p className="hint" style={{ margin: 0 }}>{status.message}</p></div>
      )}
      {stalled && !unreconciled && <div className="row" style={{ marginTop: 14 }}><button className="btn ghost" onClick={() => inputRef.current && inputRef.current.click()}>Choose a different file</button></div>}
      {ready && q !== "done" && <div className="row" style={{ marginTop: 14 }}><button className="btn big" onClick={() => go("reading")}>Show my picture {"\u2192"}</button><span className="muted" style={{ marginLeft: 10 }}>or answer these first</span></div>}
      {q !== "done" && !stalled && (
        <div className="card" style={{ marginTop: 18 }}>
          <div className="lbl">While I read this{"\u2026"}</div>
          {q === "q1" && <Q1 go={qGo} embedded household={household} setHousehold={setHousehold} setHouseholdAnswered={setHouseholdAnswered} />}
          {q === "q2" && <Q2 go={qGo} embedded priorities={priorities} setPriorities={setPriorities} />}
        </div>
      )}
      {q !== "done" && stalled && <p className="fine" style={{ marginTop: 14 }}>Your answers are saved as you go. You can finish these later on Home.</p>}
    </>
  );
}


const inr0 = (n) => "\u20B9" + Math.round(n).toLocaleString("en-IN");
function countUp(el, to, ms, fmt) {
  if (!el) return;
  if (reducedMotion()) { el.textContent = fmt(to); return; }
  let start = null;
  const step = (ts) => { if (!start) start = ts; const p = Math.min(1, (ts - start) / ms); el.textContent = fmt(to * (1 - Math.pow(1 - p, 3))); if (p < 1) requestAnimationFrame(step); };
  requestAnimationFrame(step);
}
function drawPath(root) {
  const fp = root && root.querySelector(".fpath");
  if (!fp || reducedMotion() || !fp.getTotalLength) return;
  const len = fp.getTotalLength();
  fp.style.strokeDasharray = len; fp.style.strokeDashoffset = len; fp.getBoundingClientRect();
  fp.style.transition = "stroke-dashoffset 1.4s ease"; fp.style.strokeDashoffset = 0;
}


/** "What matters most right now?" - choose up to 3, kept in the order picked (the first is the top priority). Used here and on Home. */
export function PriorityPicker({ value, onChange }) {
  const sel = value || [];
  const toggle = (k) => onChange(sel.includes(k) ? sel.filter((x) => x !== k) : sel.length < 3 ? [...sel, k] : sel);
  return (
    <>
      <ChoiceGrid options={PRIO} isSelected={(k) => sel.includes(k)} onToggle={toggle} isDisabled={(k) => sel.length >= 3 && !sel.includes(k)} />
      <p className="fine" style={{ marginTop: 10 }} aria-live="polite">{sel.length} of 3 chosen{sel.length ? " \u00B7 the first you picked is your top priority" : ""}</p>
    </>
  );
}

